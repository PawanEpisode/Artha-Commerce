"""
End-to-end check of recall R1 over real HTTP: a Django server (with `recall_system` answered locally, see `serve.py`), a freshly
generated seed deck, one throwaway student and two devices. Usage (from the repo root, with the API's virtualenv active and a
local PostgreSQL running):

    DATABASE_URL=postgres://... python scripts/e2e/recall-r1/run.py

It migrates the database, loads the shipped syllabus (idempotent), loads a small generated deck (slug `e2e-...`, retired at the
end), then prints one PASS/FAIL line per step. Exit code 1 on any failure. Only counts and ids are printed: no card text.
Run it against a local or scratch database, never production.
"""

from __future__ import annotations

import gzip  # noqa: F401 - used by capacity.py through `run`
import json
import os
import subprocess
import sys
import tempfile
import time
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path

import httpx
import jwt
import psycopg

ROOT = Path(__file__).resolve().parents[3]
API = ROOT / "apps" / "api"
HERE = Path(__file__).resolve().parent
PORT_API = 18100
SECRET = "e2e-secret-e2e-secret-e2e-secret-32b"
TICK = "e2e-recall-tick"
USER = str(uuid.uuid4())
RUN = uuid.uuid4().hex[:8]
SLUG = f"e2e-{RUN}"
MARK = f"zq{RUN}mark"  # in every card text, so the server log can be searched for a leak
ENV = {
    **os.environ,
    "DJANGO_SECRET_KEY": "e2e",
    "DJANGO_DEBUG": "true",
    "DJANGO_ALLOWED_HOSTS": "127.0.0.1,localhost",
    "SUPABASE_URL": "http://127.0.0.1:1",
    "SUPABASE_JWT_SECRET": SECRET,
    "SUPABASE_SERVICE_ROLE_KEY": "e2e-service-key",
    "POSTHOG_API_KEY": "",
    "RECALL_TICK_SECRET": TICK,
}
SCOPE = {
    "course": "cma",
    "level": "final",
    "subject_key": "corporate-and-economic-laws",
    "chapter_key": "the-companies-act-2013",
}
DECK_CARDS = 320
USER_COLUMNS = ("user_id", "owner_user_id", "reporter_user_id")
failures: list[str] = []


def check(name: str, ok: bool, detail: object = "") -> None:
    print(
        f"{'PASS' if ok else 'FAIL'}  {name}" + (f"  [{detail}]" if not ok else ""),
        flush=True,
    )
    if not ok:
        failures.append(name)


def token(user: str | None = None) -> str:
    return jwt.encode(
        {
            "sub": user or USER,
            "aud": "authenticated",
            "exp": int(time.time()) + 3600,
            "email": "e2e@example.com",
        },
        SECRET,
        algorithm="HS256",
    )


def iso(moment: datetime) -> str:
    return moment.astimezone(UTC).isoformat().replace("+00:00", "Z")


def manage(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "manage.py", *args],
        cwd=API,
        env=ENV,
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )


def seed_file(folder: Path) -> Path:
    """A generated deck of `DECK_CARDS` pointer cards in the real CMA chapter. Prompts carry a marker and no real content."""
    tiers = ("mandatory", "important", "bullet")
    items = [
        {
            "ref": f"{SLUG}-{i:04d}",
            "kind": "pointer",
            "importance": tiers[i % 3],
            "fields": {
                "prompt_md": f"{MARK} question {i}?",
                "answer_md": f"{MARK} answer {i}.",
            },
            "rights_status": "original",
        }
        for i in range(DECK_CARDS)
    ]
    data = {
        "schema": 1,
        "sample": False,
        "decks": [
            {
                "slug": SLUG,
                "title": f"End to end {RUN}",
                "description": "Generated by scripts/e2e/recall-r1/run.py.",
                "changelog": "First.",
                "scope": SCOPE,
                "items": items,
            }
        ],
    }
    path = folder / f"{SLUG}.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def start(log_path: Path | None = None) -> tuple[list[subprocess.Popen], str]:
    """Migrates, loads the syllabus and starts the API server. Returns the processes and the API base URL."""
    if not ENV.get("DATABASE_URL", "").startswith(("postgres://", "postgresql://")):
        sys.exit(
            "Set DATABASE_URL to a local PostgreSQL database (the review log is partitioned, SQLite cannot run this)."
        )
    for step in (
        ["migrate", "--noinput", "-v", "0"],
        ["load_syllabus_seed", "--publish"],
    ):
        out = manage(*step)
        if out.returncode != 0:
            sys.exit(f"manage.py {step[0]} failed:\n{out.stdout[-1500:]}\n{out.stderr[-1500:]}")
    log = open(log_path, "w") if log_path else subprocess.DEVNULL  # noqa: SIM115 - handed to Popen, closed with the process
    server = subprocess.Popen(
        [sys.executable, str(HERE / "serve.py"), f"127.0.0.1:{PORT_API}"],
        cwd=API,
        env=ENV,
        stdout=log,
        stderr=log,
    )
    base = f"http://127.0.0.1:{PORT_API}/api/v1"
    for _ in range(80):
        try:
            httpx.get(f"{base}/recall/today/", timeout=1)
            break
        except httpx.HTTPError:
            time.sleep(0.5)
    return [server], base


def pg() -> psycopg.Connection:
    return psycopg.connect(ENV["DATABASE_URL"], autocommit=True)


def rows_left(user: str) -> dict[str, int]:
    """Rows in every `recall_*` table (partitions included) that point at the student by id."""
    found: dict[str, int] = {}
    with pg() as conn:
        cols = conn.execute(
            "SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public' "
            "AND table_name LIKE 'recall\\_%%' AND column_name = ANY(%s)",
            [list(USER_COLUMNS)],
        ).fetchall()
        for table, column in cols:
            n = conn.execute(f'SELECT count(*) FROM "{table}" WHERE "{column}" = %s', [user]).fetchone()[0]
            if n:
                found[f"{table}.{column}"] = n
    return found


def partitions() -> int:
    with pg() as conn:
        return conn.execute(
            "SELECT count(*) FROM pg_inherits WHERE inhparent = 'recall_reviewlog'::regclass"
        ).fetchone()[0]


def event(card_id: str, rating: int, at: datetime, device: str, session: str | None = None) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "card_id": card_id,
        "rating": rating,
        "reviewed_at": iso(at),
        "duration_ms": 4000,
        "device_id": device,
        "session_id": session,
        "mode": "normal",
        "tz_offset_min": 330,
    }


def all_cards(client: httpx.Client) -> list[dict]:
    out: list[dict] = []
    cursor = None
    while True:
        params = {
            "limit": 100,
            "sort": "newest",
            **({"cursor": cursor} if cursor else {}),
        }
        page = client.get("/recall/cards/", params=params).json()
        out += page["items"]
        cursor = page.get("next_cursor")
        if not cursor:
            return out


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="recall-e2e-"))
    server_log = tmp / "server.log"
    procs: list[subprocess.Popen] = []
    try:
        seeds = tmp / "seed"
        seeds.mkdir()
        seed_file(seeds)
        procs, base = start(server_log)
        out = manage("load_recall_seed", str(seeds), "--publish")
        check(
            "seed loader publishes the generated deck",
            out.returncode == 0 and SLUG in out.stdout,
            out.stderr[-300:],
        )
        check(
            "review log is hash partitioned on PostgreSQL",
            partitions() == 16,
            partitions(),
        )
        client = httpx.Client(base_url=base, headers={"authorization": f"Bearer {token()}"}, timeout=60)

        # 1. Flag, auth and the library.
        check(
            "no token is refused",
            httpx.get(f"{base}/recall/today/").status_code in (401, 403),
        )
        lib = client.get("/recall/decks/library/", params={"limit": 50}).json()
        deck = next((d for d in lib.get("items", []) if d["slug"] == SLUG), None)
        check(
            "the deck shows in the library with its card count",
            bool(deck) and deck["card_count"] == DECK_CARDS,
            deck and deck["card_count"],
        )
        if not deck:
            return 1

        # 2. Subscribe: the student gets her own copy of every card; a second tap changes nothing.
        sub = client.post(
            f"/recall/decks/{deck['id']}/subscribe/",
            json={"unlock_mode": "all", "min_importance": "bullet"},
        )
        check(
            "subscribe copies the deck",
            sub.status_code == 201 and sub.json()["cards_created"] == DECK_CARDS,
            sub.text[:200],
        )
        again = client.post(
            f"/recall/decks/{deck['id']}/subscribe/",
            json={"unlock_mode": "all", "min_importance": "bullet"},
        )
        check(
            "a second subscribe creates nothing",
            again.status_code == 200 and again.json()["cards_created"] == 0,
            again.text[:200],
        )
        cards = all_cards(client)
        ids = [c["id"] for c in cards]
        check(
            f"{DECK_CARDS} cards are listed with no duplicates",
            len(ids) == DECK_CARDS and len(set(ids)) == DECK_CARDS,
            len(ids),
        )

        # 3. 200 cards online: 150 are backdated so they are overdue later (the catch-up backlog), 50 are today.
        now = datetime.now(UTC)
        sess = client.post(
            "/recall/sessions/",
            json={
                "client_id": str(uuid.uuid4()),
                "source": "today",
                "planned_count": 50,
                "tz": "Asia/Kolkata",
            },
        )
        check("a session opens", sess.status_code == 201, sess.text[:200])
        session_id = sess.json()["id"]
        online: list[dict] = []
        for i, card_id in enumerate(ids[:200]):
            if i < 150:
                ev = event(
                    card_id,
                    4,
                    now - timedelta(days=25 + i % 4, minutes=i),
                    "web-laptop",
                )
            else:
                ev = event(
                    card_id,
                    1 + (i % 4),
                    now - timedelta(minutes=400 - i),
                    "web-laptop",
                    session_id,
                )
            online.append(ev)
        statuses = []
        for ev in sorted(online, key=lambda e: e["reviewed_at"]):
            r = client.post("/recall/reviews/", json=ev)
            statuses.append((r.status_code, r.json().get("status")))
        check(
            "200 online reviews are applied",
            statuses.count((201, "applied")) == 200,
            set(statuses),
        )
        dup = client.post("/recall/reviews/", json=online[7])
        check(
            "the same client event id twice is a duplicate, not a second review",
            dup.status_code == 200 and dup.json()["status"] == "duplicate",
            dup.text[:200],
        )
        closed = client.post(f"/recall/sessions/{session_id}/close/").json()
        check(
            "the session closes with a summary",
            closed.get("status") == "closed" and closed["summary"] is not None,
            closed.get("status"),
        )

        # 4. Undo the last review; asking twice is safe.
        last = max(online, key=lambda e: e["reviewed_at"])
        undo = {"undo_id": str(uuid.uuid4()), "voids_id": last["id"]}
        u1 = client.post("/recall/reviews/undo/", json=undo)
        u2 = client.post("/recall/reviews/undo/", json=undo)
        check(
            "undo rewinds the card",
            u1.status_code == 200 and u1.json()["card"]["reps"] == 0,
            u1.text[:200],
        )
        check(
            "undo twice is idempotent",
            u2.status_code == 200 and u2.json()["undo_id"] == undo["undo_id"],
            u2.text[:200],
        )

        # 5. 100 cards offline from two devices. Cards 240 to 259 are reviewed on both; for half of them the second device's
        #    review is older than the first one's, so it arrives as a past fact and the card is folded again.
        base_time = now - timedelta(hours=3)
        phone = [event(c, 3, base_time + timedelta(minutes=2 * i), "phone") for i, c in enumerate(ids[200:260])]
        laptop = []
        for i, c in enumerate(ids[240:300]):
            overlap = i < 20
            when = base_time + timedelta(
                minutes=2 * (40 + i) + (-90 if overlap and i % 2 == 0 else 0),
                seconds=30,
            )
            laptop.append(event(c, 4 if overlap else 3, when, "laptop"))
        r1 = client.post("/recall/reviews/batch/", json={"events": phone})
        r2 = client.post("/recall/reviews/batch/", json={"events": laptop})
        applied = [x["status"] for x in r1.json()["results"] + r2.json()["results"]]
        merged = sum(x["merged"] for x in r2.json()["results"])
        check(
            "both offline batches apply (120 events over 100 cards)",
            applied.count("applied") == 120,
            set(applied),
        )
        check("older facts arriving late are merged by replay", merged >= 1, merged)
        resend = client.post("/recall/reviews/batch/", json={"events": phone + laptop[:40]})
        again_status = {x["status"] for x in resend.json()["results"]}
        check(
            "sending the same batches again only returns duplicates",
            again_status == {"duplicate"},
            again_status,
        )
        bad = client.post(
            "/recall/reviews/batch/",
            json={"events": [event(ids[0], 3, now, "x") for _ in range(101)]},
        )
        check(
            "a batch over 100 events is refused",
            bad.status_code == 422 and bad.json()["error"]["code"] == "batch_too_large",
            bad.text[:200],
        )

        # 6. Nothing lost, nothing counted twice, every card equals the fold of its log.
        exported = client.get("/recall/export/").json()
        review_ids = [r["id"] for r in exported["reviews"] if r["kind"] == "review"]
        sent = {e["id"] for e in online + phone + laptop}
        check(
            "every review sent is in the log exactly once",
            len(review_ids) == 320 and set(review_ids) == sent,
            (len(review_ids), len(sent - set(review_ids))),
        )
        by_card = {c["id"]: c for c in exported["cards"]}
        reps = {i: by_card[i]["reps"] for i in ids}
        check(
            "reps match the reviews: 1 each, 2 on the 20 shared cards, 0 on the undone one",
            sum(1 for i in ids[240:260] if reps[i] == 2) == 20
            and sum(1 for i in ids[200:240] + ids[260:300] if reps[i] == 1) == 80
            and reps[last["card_id"]] == 0,
            sorted(set(reps.values())),
        )
        replay = manage("recall_replay", "--user", USER)
        check(
            "replaying every card from the log changes nothing",
            replay.returncode == 0 and "0 changed" in replay.stdout,
            replay.stdout[-200:],
        )

        # 7. Catch-up: 150 reviews are weeks overdue. Rebalance spreads them and a second run has nothing to move.
        today = client.get("/recall/today/", params={"tz": "Asia/Kolkata"}).json()
        check(
            "a backlog switches today to catch-up mode",
            today["mode"] == "catchup",
            (today["mode"], today["counts"]),
        )
        before = today["catchup"]["due"]
        reb = client.post("/recall/catchup/rebalance/", json={"days": 7})
        check(
            "rebalance moves the overflow to later days",
            reb.status_code == 200 and reb.json()["moved"] > 0,
            reb.text[:200],
        )
        after = client.get("/recall/today/", params={"tz": "Asia/Kolkata"}).json()["catchup"]["due"]
        check("fewer reviews are due today afterwards", after < before, (before, after))
        check(
            "a second rebalance moves nothing",
            client.post("/recall/catchup/rebalance/", json={"days": 7}).json()["moved"] == 0,
        )

        # 8. The rest of the read side answers, and the tick needs its secret.
        queue = client.get("/recall/queue/", params={"limit": 20}).json()
        check(
            "the queue serves up to 20 cards",
            0 < len(queue["cards"]) <= 20,
            len(queue["cards"]),
        )
        pack = client.get("/recall/pack/", params={"limit": 300})
        check(
            "the offline pack has cards, weights and an id",
            pack.status_code == 200
            and pack.json()["cards"]
            and len(pack.json()["weights"]) == 21
            and pack.json()["pack_id"],
            pack.text[:120],
        )
        stats = client.get("/recall/stats/summary/")
        cached = client.get(
            "/recall/stats/summary/",
            headers={"if-none-match": stats.headers.get("etag", "")},
        )
        check(
            "stats answer and honour If-None-Match",
            stats.status_code == 200 and cached.status_code == 304,
            (stats.status_code, cached.status_code),
        )
        check(
            "forgotten list answers",
            client.get("/recall/forgotten/").status_code == 200,
        )
        put = client.put("/recall/settings/", json={"new_per_day": 5})
        check(
            "settings can be changed",
            put.status_code == 200 and put.json()["new_per_day"] == 5,
            put.text[:200],
        )
        check(
            "vacation can be set and cleared",
            client.put("/recall/vacation/", json={"until": None}).status_code == 200,
        )
        check(
            "tick with the secret works",
            httpx.post(f"{base}/recall/internal/tick/", headers={"X-Recall-Tick-Secret": TICK}).status_code == 200,
        )
        check(
            "tick without the secret is refused",
            httpx.post(f"{base}/recall/internal/tick/").status_code in (401, 403),
        )

        # 9. Export: JSON and both CSV files finish with a completion marker.
        for name, rows in (("cards", 320), ("reviews", 321)):
            text = client.get(f"/recall/export/{name}.csv").text.strip().splitlines()
            check(
                f"{name}.csv is complete ({rows} rows)",
                text[-1] == f"#complete,{rows}",
                text[-1],
            )
        check(
            "the JSON export holds 320 cards and the settings",
            len(exported["cards"]) == 320 and exported["settings"] is not None,
        )

        # 10. Erase: wrong word refused, right word removes everything, then nothing is reachable by the student's id.
        check(
            "erase needs the typed word",
            client.post("/recall/erase/", json={"confirm": "no"}).status_code == 400,
        )
        check(
            "the student has rows before erasing",
            bool(rows_left(USER)),
            rows_left(USER),
        )
        gone = client.post("/recall/erase/", json={"confirm": "ERASE"})
        check(
            "erase answers with counts",
            gone.status_code == 200 and gone.json()["deleted"]["cards"] == 320,
            gone.text[:200],
        )
        left = rows_left(USER)
        check(
            "no recall table (log partitions included) holds a row for the student",
            left == {},
            left,
        )
        empty = client.get("/recall/export/").json()
        check(
            "the export is empty afterwards",
            not empty["cards"] and not empty["reviews"] and empty["settings"] is None,
        )
        # (export and erase share the recall_export throttle of 6 an hour, and this run uses exactly six calls)

        # 11. The platform deck is not the student's: it is still there, and no card text reached the server log.
        with pg() as conn:
            deck_rows = conn.execute("SELECT count(*) FROM recall_deck WHERE slug = %s", [SLUG]).fetchone()[0]
            conn.execute("UPDATE recall_deck SET status = 'withdrawn' WHERE slug = %s", [SLUG])  # out of the library
        check("erase leaves the platform deck alone", deck_rows == 1, deck_rows)
        for p in procs:
            p.terminate()
        procs = []
        time.sleep(1)
        log = server_log.read_text(errors="replace")
        check(
            "the server log holds no card text",
            MARK not in log and "question" not in log.lower().replace("questions", ""),
            len(log),
        )
    finally:
        for p in procs:
            p.terminate()
    print(f"\n{'ALL PASSED' if not failures else f'{len(failures)} FAILED: ' + ', '.join(failures)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
